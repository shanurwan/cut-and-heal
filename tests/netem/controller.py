"""Controller for the kernel-level shaping test.

Serves real setup and plan text, generated by the same functions a run uses, to real shaper
sidecars in plain Docker containers. No Kubernetes: this test is about whether the compiled
`tc` commands do to packets what plan.py says they do.
"""

from __future__ import annotations

import asyncio
import json
import os
from pathlib import Path

from aiohttp import web

from cutandheal.controller import State, make_app, now_ms, plan_text
from cutandheal.model import Scenario
from cutandheal.plan import Pod, Topology, check_topology, open_set, setup_commands

SUBNET = os.environ.get("CAH_TEST_SUBNET", "172.31.60")
OUT = Path("/out")
SEED = 3

SCN = Scenario.model_validate(
    {
        "name": "netem-test",
        "title": "kernel-level shaping test",
        "regions": {
            "inside": {"nodes": 2, "domestic": {"delay_ms": 5}},
            "outside": {"nodes": 1, "domestic": {"delay_ms": 5}},
        },
        "borders": {"edge": {"between": ["inside", "outside"], "gated": "inside", "healthy": {"delay_ms": 40}}},
        "bootstrap_region": "outside",
        "timeline": [
            {"name": "baseline", "duration_s": 30},
            {"name": "cut", "duration_s": 30, "borders": {"edge": {"open_nodes": 0}}},
            {"name": "bridge", "duration_s": 30, "borders": {"edge": {"open_nodes": 1}}},
            {"name": "healed", "duration_s": 30},
        ],
    }
)
TOPO = Topology(
    pods=(
        Pod("inside-0", "inside", f"{SUBNET}.10", "docker"),
        Pod("inside-1", "inside", f"{SUBNET}.11", "docker"),
        Pod("outside-0", "outside", f"{SUBNET}.70", "docker"),
    ),
    region_cidrs={"inside": (f"{SUBNET}.0/26",), "outside": (f"{SUBNET}.64/26",)},
)


async def main() -> None:
    assert check_topology(SCN, TOPO) == []
    state = State()
    runner = web.AppRunner(make_app(state), access_log=None)
    await runner.setup()
    await web.TCPSite(runner, "0.0.0.0", 8080).start()

    names = {p.name for p in TOPO.pods}
    state.setup = {p.name: "\n".join(" ".join(c) for c in setup_commands(SCN, TOPO, p)) + "\n" for p in TOPO.pods}
    for _ in range(120):
        if state.acked("setup") == names:
            break
        await asyncio.sleep(0.5)
    else:
        raise SystemExit(f"setup acknowledged only by {sorted(state.acked('setup'))}")

    t0 = now_ms() + 8000
    state.plan = {p.name: plan_text(SCN, TOPO, p, SEED, t0) for p in TOPO.pods}
    bridge = open_set(SCN, TOPO, "edge", 2, SEED)
    (OUT / "open").write_text(next(iter(bridge)))
    (OUT / "t0").write_text(str(t0 // 1000))

    await asyncio.sleep((t0 - now_ms()) / 1000 + SCN.duration_s + 4)
    (OUT / "acks.json").write_text(json.dumps(state.acks))
    await asyncio.Event().wait()


asyncio.run(main())
